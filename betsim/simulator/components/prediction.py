import taipy.gui.builder as tgb

from betsim.simulator.components.common import tgb_header, tgb_placeholder
from betsim.simulator.actions.bet import (
    await_acknowledgement,
    predict_result,
    reset_fixture,
    update_bet_readiness,
)


def tgb_bet_details(layout: str = "1 2 3 2 1", width: str = "20vw") -> None:
    with tgb.part():
        with tgb.layout(layout):
            tgb_placeholder()
            tgb.number(
                "{hcap_mag}",
                label="Handicap",
                step=0.25,
                min=-3,
                max=3,
                width=width,
                on_change=update_bet_readiness,
            )
            tgb.button(
                "Predict",
                on_action=await_acknowledgement,
                active="{is_betable}",
            )
            tgb.selector(
                "{risk_attitude}",
                label="Risk Attitude",
                dropdown=True,
                width=width,
                lov="{option_risk}",
                on_change=update_bet_readiness,
            )
            tgb_placeholder()

        with tgb.part(render="{not is_betable}"):
            tgb.text(
                (
                    "##### _Input both handicap and risk attitude, "
                    "then click Predict to simulate the result._"
                ),
                mode="md",
            )


def tgb_video() -> None:
    with tgb.part():
        with tgb.html(
            "video",
            autoplay="autoplay",
            controls="controls",
            playsinline="playsinline",
            preload="auto",
            src="assets/videos/prediction_transition.mp4",
            width="480",
        ):
            tgb.html("p", "Prediction transition video is unavailable.")


def tgb_bet_prediction() -> None:
    with tgb.dialog(
        "{is_acknowledge}",
        on_action=predict_result,
        labels=["Accept", "Cancel"],
        title="Acknowledgement",
    ):
        tgb.text(
            (
                "This prediction is generated by a machine learning model and "
                "is provided solely for informational purposes. It does not "
                "constitute betting advice, and any reliance on it is at your "
                "own risk."
            ),
            mode="md",
        )

        with tgb.part("text-center", render="{is_transit}"):
            tgb_video()
            tgb.text("##### Handicap result is simulating...", mode="md")

    with tgb.part(render="{is_predict}"):
        tgb.text("{summary}", mode="md")
        tgb.button(
            "Reset",
            on_action=reset_fixture,
        )


def tgb_prediction() -> None:
    with tgb.part(render="{is_fixture}"):
        tgb_placeholder("---")
        tgb_header("#### Handicap Prediction")
        tgb_bet_details()
        tgb_bet_prediction()
